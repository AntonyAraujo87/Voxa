import { build } from 'esbuild';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
await build({entryPoints:['src/lib/iceLease.ts'],bundle:true,platform:'node',format:'cjs',outfile:'work/ice-lease-subject.cjs'});
const {IceLease}=createRequire(import.meta.url)('../work/ice-lease-subject.cjs');
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let resolveFetch, calls=0, applied=[];
const lease=new IceLease(()=>{calls++; return new Promise(resolve=>{resolveFetch=resolve;});},value=>applied.push(value),()=>true);
lease.start([{urls:'turn:old.example'}]);
const first=lease.refresh(); const duplicate=lease.refresh();
assert.equal(first,duplicate); assert.equal(calls,1);
lease.stop(); resolveFetch([{urls:'turn:stale.example'}]); await first;
assert.equal(applied.length,1,'resposta apos sair nao altera credenciais');
let attempts=0;
const retry=new IceLease(async()=>{if(++attempts===1)throw Error('temporary');return [{urls:'turn:renewed.example'}];},value=>applied.push(value),()=>true,{refresh:60000,retry:10,maxRetry:20});
retry.start([]);
assert.equal(await retry.refresh(),false);
await wait(60);
assert.equal(attempts,2,'falha temporaria deve renovar sem esperar 40 minutos');
assert.equal(applied.at(-1)[0].urls,'turn:renewed.example'); retry.stop();
let offline=true;
const reconnect=new IceLease(async()=>{calls++;return [];},()=>{},()=>!offline,{refresh:60000,retry:10,maxRetry:20});
reconnect.start([]); const before=calls;
assert.equal(await reconnect.refresh(),false);assert.equal(calls,before);
offline=false;assert.equal(await reconnect.refresh(),true);reconnect.stop();
await build({entryPoints:['src/lib/resumeWatch.ts'],bundle:true,platform:'node',format:'cjs',outfile:'work/resume-watch-subject.cjs'});
const {watchResume}=createRequire(import.meta.url)('../work/resume-watch-subject.cjs');
const originalNow=Date.now;
const originalNavigator=Object.getOwnPropertyDescriptor(globalThis,'navigator');
let now=100_000, tick, recoveries=0, finishRecovery;
const network=new EventTarget();
globalThis.window=new EventTarget();
window.setInterval=fn=>{tick=fn;return 1;};window.clearInterval=()=>{tick=null;};
globalThis.document=new EventTarget();
Object.defineProperty(globalThis,'navigator',{value:{connection:network},configurable:true});
Date.now=()=>now;
try {
  const dispose=watchResume(()=>{recoveries++;return new Promise(resolve=>{finishRecovery=resolve;});});
  now+=15_000;tick();assert.equal(recoveries,0,'intervalo normal nao reinicia rede');
  now+=61_000;tick();assert.equal(recoveries,1,'retorno da suspensao recupera');
  window.dispatchEvent(new Event('online'));network.dispatchEvent(new Event('change'));
  assert.equal(recoveries,1,'eventos simultaneos nao duplicam recuperacao');
  finishRecovery();await wait(0);
  now-=120_000;tick();assert.equal(recoveries,2,'relogio retrocedendo nao bloqueia recuperacao');
  finishRecovery();await wait(0);
  now+=1000;network.dispatchEvent(new Event('change'));assert.equal(recoveries,2,'debounce evita tempestade');
  now+=6000;network.dispatchEvent(new Event('change'));assert.equal(recoveries,3,'troca de interface recupera');
  finishRecovery();await wait(0);dispose();
  now+=61_000;window.dispatchEvent(new Event('online'));network.dispatchEvent(new Event('change'));document.dispatchEvent(new Event('visibilitychange'));
  assert.equal(recoveries,3);assert.equal(tick,null,'dispose remove timer e listeners');
}finally{
  Date.now=originalNow;delete globalThis.window;delete globalThis.document;
  if(originalNavigator)Object.defineProperty(globalThis,'navigator',originalNavigator);else delete globalThis.navigator;
}
console.log('PASS: TURN (4 verificacoes) e suspensao/rede/relogio/cancelamento (7 verificacoes)');
